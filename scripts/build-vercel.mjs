#!/usr/bin/env node
// Static build of the console for Vercel (https://leash-console.vercel.app): the landing plus the console in
// its hosted, verify-only mode (NEXT_PUBLIC_LEASH_VERIFY_ONLY=1, see apps/web/lib/mode.ts). There is no owner
// device behind it, so the build has no API routes and no server code; Vercel routes /api/* to the
// verify-only gateway on the VPS, and answers the owner-device and PayPal routes itself with the gateway's
// own Setup text. The committed proof fixture is served beside the page for the console's Live verify.
//
//   node scripts/build-vercel.mjs --out <folder outside the repo> [--gateway https://leash-api.example]
//   vercel deploy <folder> --prod --yes --project leash-console
//
// Build @leash/core first (pnpm --filter @leash/core build) if the web app's type imports need it.
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'apps/web');
const stage = join(web, '.next-vercel-stage');

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) return fallback;
  const v = process.argv[i + 1];
  if (v === undefined || v.startsWith('--')) fail(`--${name} needs a value`);
  return v;
}
function fail(message) {
  console.error(`build-vercel: ${message}`);
  process.exit(1);
}

const outArg = arg('out');
if (!outArg) fail('--out <folder> is required (a folder outside the repo; it is replaced)');
const out = resolve(outArg);
if (!relative(root, out).startsWith('..')) fail(`refusing to write ${out}: pick a folder outside the repo`);
const gateway = arg('gateway', 'https://leash-api.201-18-198-162.sslip.io').replace(/\/+$/, '');
if (!/^https:\/\/[A-Za-z0-9.-]+(:\d+)?$/.test(gateway)) fail(`--gateway must be an https origin, got ${gateway}`);

// 1. Stage apps/web without the API routes and the server-only module. --out is emptied first, so a
// failed build never leaves an older export behind to be deployed by mistake.
rmSync(out, { recursive: true, force: true });
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
cpSync(join(web, 'app'), join(stage, 'app'), { recursive: true, filter: (s) => relative(join(web, 'app'), s).split(/[\\/]/)[0] !== 'api' });
cpSync(join(web, 'components'), join(stage, 'components'), { recursive: true });
cpSync(join(web, 'lib'), join(stage, 'lib'), { recursive: true, filter: (s) => !s.endsWith('server.ts') });
for (const f of ['tsconfig.json', 'tailwind.config.ts', 'postcss.config.mjs', 'next-env.d.ts']) cpSync(join(web, f), join(stage, f));
// Static files (/mezo/deployment.json, and /mezo/hero.webp once it exists) are exported beside the pages.
if (existsSync(join(web, 'public'))) cpSync(join(web, 'public'), join(stage, 'public'), { recursive: true });
writeFileSync(join(stage, 'next.config.mjs'), `// Generated by scripts/build-vercel.mjs\nexport default { output: 'export', images: { unoptimized: true } };\n`);

// 2. Build with the hosted flag. next resolves from apps/web/node_modules (the stage sits inside it).
const require = createRequire(join(web, 'package.json'));
const nextBin = join(dirname(require.resolve('next/package.json')), 'dist/bin/next');
const result = spawnSync(process.execPath, [nextBin, 'build'], {
  cwd: stage,
  stdio: 'inherit',
  env: { ...process.env, NEXT_PUBLIC_LEASH_VERIFY_ONLY: '1', NEXT_TELEMETRY_DISABLED: '1' },
});
if (result.status !== 0) {
  rmSync(stage, { recursive: true, force: true });
  fail(`next build exited with ${result.status}`);
}

// 3. The export, the fixture proof, the Setup answers and the routes.
rmSync(out, { recursive: true, force: true });
cpSync(join(stage, 'out'), out, { recursive: true }); // a copy: --out may be on another volume
rmSync(stage, { recursive: true, force: true });
const fixture = join(root, 'contracts/test/fixtures/base');
if (!existsSync(join(fixture, 'proof'))) fail(`missing ${fixture}/proof`);
mkdirSync(join(out, 'fixtures/base'), { recursive: true });
for (const f of ['proof', 'public_inputs']) cpSync(join(fixture, f), join(out, 'fixtures/base', f));
mkdirSync(join(out, '_setup'), { recursive: true });
writeFileSync(join(out, '_setup/owner-device.json'), JSON.stringify({ success: false, kind: 'setup', error: 'This gateway is verify-only: proving runs on the owner device (leash-mcp, or the console with LEASH_OWNER_DEVICE=1).' }));
writeFileSync(join(out, '_setup/paypal.json'), JSON.stringify({ success: false, kind: 'setup', error: 'Setup required (PAYPAL_CLIENT_ID): the verify-only gateway has no PayPal sandbox keys and no pay route.' }));
const json = { 'content-type': 'application/json', 'cache-control': 'no-store' };
writeFileSync(join(out, 'vercel.json'), JSON.stringify({
  routes: [
    { src: '/api/policies', methods: ['POST'], status: 403, headers: json, dest: '/_setup/owner-device.json' },
    { src: '/api/(prove|harness|paypal/vault)', status: 403, headers: json, dest: '/_setup/owner-device.json' },
    { src: '/api/pay(/capture)?', status: 503, headers: json, dest: '/_setup/paypal.json' },
    { src: '/api/(.*)', dest: `${gateway}/api/$1` },
    { src: '/fixtures/base/(proof|public_inputs)', headers: { 'content-type': 'application/octet-stream' }, continue: true },
    // The orchestrator fills deployment.json after the live Mezo deploy: never serve a stale copy.
    { src: '/mezo/deployment\\.json', headers: { 'cache-control': 'no-store' }, continue: true },
    // /mezo is exported as mezo.html beside a mezo/ data folder: route it before the filesystem sees the folder.
    { src: '/mezo/?', dest: '/mezo.html' },
    { handle: 'filesystem' },
    // The static export writes /evidence as evidence.html; the landing links /evidence.
    { src: '/evidence/?', dest: '/evidence.html' },
  ],
}, null, 2));
console.log(`build-vercel: ${out} (${readdirSync(out).length} entries), /api/* -> ${gateway}`);
